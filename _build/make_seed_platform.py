_NUM_KEYS = {"价格", "销量", "销售额", "环比增速", "关联达人数", "退货率",
             "评分", "评价数", "预估成本"}
_SEL_KEYS = {"品类", "数据来源", "所属市场", "剂型", "技术壁垒", "备案路径",
             "宣称支撑难度", "与我方价格带匹配", "与我方客群匹配",
             "与我方 SKU 重合度", "决策状态", "数据标记"}
_DATE_KEYS = {"上市日期"}


def wrap(name, value):
    """按字段名映射到后端要求的 {type_key: value} 结构。"""
    if name in _NUM_KEYS:
        return {"number": value}
    if name in _SEL_KEYS:
        return {"select": value}
    if name in _DATE_KEYS:
        return {"date": value}
    return {"text": value}


